-- "Пустое место" в сетке альбома: заглушка, которую владелец добавляет в
-- админке, чтобы расставлять фото свободно. Хранится как строка в photo
-- (так она сама участвует в сортировке и перетаскивании наравне с фото),
-- но без файла: file_url/thumb_url пустые, is_spacer = 1. На сайте на её
-- месте — пустой блок нужной пропорции (grid_class_id).
--
-- ВЫПОЛНИТЬ В phpMyAdmin ДО заливки нового __init__.py: новый код читает
-- эту колонку, и без неё альбомы перестанут открываться.

ALTER TABLE `photo`
  ADD COLUMN `is_spacer` TINYINT(1) NOT NULL DEFAULT 0
  COMMENT 'Пустое место (заглушка) в сетке альбома, без файла'
  AFTER `album_id`;
