-- Исходное имя файла фото — ровно как оно было у фотографа на компьютере
-- ("DSC01234.jpg", "У кафе (1).jpg"). Показывается в админке во вкладке
-- «Выбор клиентов», чтобы найти отобранные клиентом фото среди RAW поиском
-- по имени. Имя файла на сервере для этого не годится: там кириллица уже
-- переведена в латиницу и спереди случайный префикс. У фото, загруженных
-- до этой колонки, тут NULL — для них имя восстанавливается из file_url
-- (см. _original_photo_name в __init__.py).
--
-- ВЫПОЛНИТЬ В phpMyAdmin ДО заливки нового __init__.py: новый код пишет
-- в эту колонку при загрузке фото, и без неё загрузка перестанет работать.

ALTER TABLE `photo`
  ADD COLUMN `original_filename` VARCHAR(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL
  COMMENT 'Исходное имя файла при загрузке (для поиска среди RAW)'
  AFTER `title`;
